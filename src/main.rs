use eframe::egui;
use std::path::PathBuf;

fn main() -> eframe::Result {
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("cheapedit")
            .with_inner_size([1360.0, 840.0])
            .with_min_inner_size([1000.0, 600.0])
            .with_drag_and_drop(true)
            .with_icon(icon()),
        renderer: eframe::Renderer::Glow,
        ..Default::default()
    };
    // "Edit with cheapedit" in Explorer passes the file as the first argument.
    let open_arg = std::env::args_os().nth(1).map(PathBuf::from).filter(|p| p.is_file());
    eframe::run_native(
        "cheapedit",
        options,
        Box::new(move |cc| {
            theme::apply(&cc.egui_ctx);
            let log = log::Log::new();
            log.info("cheapedit started");
            log.info(format!("Version {}{}", update::CURRENT, if winutil::is_dev() { " (dev build)" } else { "" }));
            let mut app = App {
                report: deps::check_all(),
                screen: Screen::Setup,
                editor: None,
                updater: update::Updater::new(log.clone()),
                show_about: false,
                download_started: false,
                log,
                open_arg,
                title: String::new(),
            };
            // Skip the setup screen when everything is already in place.
            if app.report.all_ok() {
                app.enter_editor(&cc.egui_ctx);
            }
            if !winutil::is_dev() && settings::Settings::load().updates.check_on_startup {
                app.updater.check(&cc.egui_ctx);
            }
            Ok(Box::new(app))
        }),
    )
}

/// Window icon, generated by `cargo run --example make_icon`.
fn icon() -> egui::IconData {
    const RGBA: &[u8] = include_bytes!("../assets/icon-64.rgba");
    egui::IconData { rgba: RGBA.to_vec(), width: 64, height: 64 }
}

#[derive(PartialEq)]
enum Screen {
    Setup,
    Editor,
}

struct App {
    report: deps::Report,
    screen: Screen,
    editor: Option<editor::Editor>,
    updater: update::Updater,
    show_about: bool,
    /// Only show update failures in the banner once the user asked to download.
    download_started: bool,
    log: log::Log,
    open_arg: Option<PathBuf>,
    title: String,
}

impl App {
    fn enter_editor(&mut self, ctx: &egui::Context) {
        if self.editor.is_none() {
            let (Some(ffmpeg), Some(ffprobe), Some(api)) = (self.report.ffmpeg.path().cloned(), self.report.ffprobe.path().cloned(), self.report.mpv_api.clone()) else {
                return;
            };
            let mut ed = editor::Editor::new(ffmpeg, ffprobe, api, self.log.clone(), ctx);
            if let Some(p) = self.open_arg.take() {
                ed.request_open(p);
            }
            self.editor = Some(ed);
        }
        self.screen = Screen::Editor;
    }

    fn exporting(&self) -> bool {
        self.editor.as_ref().is_some_and(|e| e.exporting())
    }

    /// The strip across the top when a new version is available or downloading.
    fn update_banner(&mut self, ui: &mut egui::Ui) {
        use update::State;
        let state = self.updater.state();
        let show = match &state {
            State::Available(_) => !self.updater.dismissed,
            State::Downloading { .. } | State::Ready { .. } | State::Installing => true,
            State::Failed(_) => self.download_started && !self.updater.dismissed,
            _ => false,
        };
        if !show {
            return;
        }
        let ctx = ui.ctx().clone();
        egui::Panel::top("update_banner")
            .frame(egui::Frame::new().fill(theme::ACCENT_DIM.gamma_multiply(0.6)).inner_margin(egui::Margin::symmetric(10, 6)))
            .show(ui, |ui| {
                ui.horizontal(|ui| match &state {
                    State::Available(r) => {
                        ui.label(egui::RichText::new(format!("cheapedit {} is available", r.version)).strong());
                        ui.label(egui::RichText::new(format!("(you have {})", update::CURRENT)).small().color(theme::MUTED));
                        let busy = self.exporting();
                        let btn = ui.add_enabled(!busy, theme::primary_button("Update now"));
                        let btn = if busy { btn.on_disabled_hover_text("Finish or cancel your export first.") } else { btn.on_hover_text("Downloads the installer, checks it, then updates and reopens cheapedit. Your settings are kept.") };
                        if btn.clicked() {
                            self.download_started = true;
                            self.updater.download(&ctx);
                        }
                        if ui.button("What's new").clicked() {
                            self.show_about = true;
                        }
                        if ui.button("Later").clicked() {
                            self.updater.dismissed = true;
                        }
                    }
                    State::Downloading { release, got } => {
                        ui.label(format!("Downloading cheapedit {}…", release.version));
                        let frac = if release.size > 0 { *got as f32 / release.size as f32 } else { 0.0 };
                        ui.add(egui::ProgressBar::new(frac.clamp(0.0, 1.0)).desired_width(220.0).show_percentage());
                    }
                    State::Ready { release, .. } => {
                        if self.exporting() {
                            ui.label(format!("cheapedit {} is ready to install. It will start when your export finishes.", release.version));
                        } else {
                            match self.updater.launch_installer() {
                                Ok(()) => ctx.send_viewport_cmd(egui::ViewportCommand::Close),
                                Err(e) => {
                                    self.log.error(&e);
                                    ui.label(egui::RichText::new(e).color(theme::DANGER));
                                }
                            }
                        }
                    }
                    State::Installing => {
                        ui.spinner();
                        ui.label("Installing the update. cheapedit will reopen by itself.");
                    }
                    State::Failed(e) => {
                        ui.label(egui::RichText::new(format!("Update failed: {e}")).color(theme::WARN));
                        if ui.button("Dismiss").clicked() {
                            self.updater.dismissed = true;
                        }
                    }
                    _ => {}
                });
            });
    }

    fn about_window(&mut self, ctx: &egui::Context) {
        use update::State;
        let mut open = self.show_about;
        egui::Window::new("About cheapedit").open(&mut open).collapsible(false).resizable(false).default_width(420.0).show(ctx, |ui| {
            ui.horizontal(|ui| {
                ui.label(egui::RichText::new(format!("cheapedit {}", update::CURRENT)).strong().size(16.0));
                if winutil::is_dev() {
                    editor::dev_badge(ui);
                }
            });
            theme::hint(ui, "A simple front end for FFmpeg. FFmpeg does the editing; libmpv plays the video.");
            ui.add_space(8.0);
            ui.label(egui::RichText::new("Updates").strong());
            if winutil::is_dev() {
                theme::hint(ui, "This is a development build, so it never checks for updates and uses its own settings (in %APPDATA%\\cheapedit-dev). The installed copy updates itself.");
            } else {
                if let Some(ed) = &mut self.editor {
                    ui.checkbox(&mut ed.settings_mut().updates.check_on_startup, "Check for updates when cheapedit starts");
                }
                theme::hint(ui, format!("The check asks github.com/{} for the latest version number. Nothing about you or your videos is sent, and nothing installs without your click.", update::REPO));
                ui.add_space(4.0);
                let state = self.updater.state();
                ui.horizontal(|ui| {
                    if ui.add_enabled(!self.updater.busy(), egui::Button::new("Check now")).clicked() {
                        self.updater.check(ctx);
                    }
                    match &state {
                        State::Checking => {
                            ui.spinner();
                            ui.label("Checking…");
                        }
                        State::UpToDate => {
                            ui.label(egui::RichText::new("You have the latest version.").color(theme::OK));
                        }
                        State::Available(r) => {
                            ui.label(egui::RichText::new(format!("Version {} is available.", r.version)).color(theme::CORAL));
                        }
                        State::Failed(e) => {
                            ui.label(egui::RichText::new(e).small().color(theme::WARN));
                        }
                        _ => {}
                    }
                });
                if let State::Available(r) = &state {
                    if self.updater.dismissed && ui.button("Show the update bar again").clicked() {
                        self.updater.dismissed = false;
                    }
                    if !r.notes.is_empty() {
                        ui.add_space(6.0);
                        ui.label(egui::RichText::new(format!("What's new in {}", r.version)).strong());
                        theme::code_frame().show(ui, |ui| {
                            egui::ScrollArea::vertical().max_height(180.0).show(ui, |ui| {
                                ui.label(&r.notes);
                            });
                        });
                    }
                }
            }
            ui.add_space(6.0);
            ui.hyperlink_to("All releases on GitHub", update::releases_page());
        });
        self.show_about = open;
    }
}

impl eframe::App for App {
    fn ui(&mut self, ui: &mut egui::Ui, frame: &mut eframe::Frame) {
        let ctx = ui.ctx().clone();
        self.update_banner(ui);
        match self.screen {
            Screen::Setup => {
                egui::CentralPanel::default_margins().show(ui, |ui| {
                    ui.vertical_centered(|ui| {
                        let has_editor = self.editor.is_some();
                        match setup_ui::show(ui, &self.report, has_editor) {
                            setup_ui::SetupAction::CheckAgain => {
                                // Keep the libmpv that the running editor already uses.
                                let api = self.report.mpv_api.clone();
                                self.report = deps::check_all();
                                if has_editor && self.report.mpv_api.is_none() {
                                    self.report.mpv_api = api;
                                }
                                self.log.info("Re-checked FFmpeg, ffprobe and libmpv.");
                            }
                            setup_ui::SetupAction::Continue => self.enter_editor(&ctx),
                            setup_ui::SetupAction::None => {}
                        }
                    });
                });
            }
            Screen::Editor => {
                if let Some(ed) = &mut self.editor {
                    match ed.ui(ui, frame) {
                        editor::EditorAction::OpenSetup => self.screen = Screen::Setup,
                        editor::EditorAction::ShowAbout => self.show_about = true,
                        editor::EditorAction::None => {}
                    }
                }
            }
        }
        if self.show_about {
            self.about_window(&ctx);
        }
        let mut title = match (&self.screen, &self.editor) {
            (Screen::Editor, Some(ed)) => ed.title(),
            _ => "cheapedit — setup".into(),
        };
        if winutil::is_dev() {
            title.push_str("  [DEV]");
        }
        if title != self.title {
            ctx.send_viewport_cmd(egui::ViewportCommand::Title(title.clone()));
            self.title = title;
        }
    }

    fn on_exit(&mut self, gl: Option<&eframe::glow::Context>) {
        if let Some(ed) = &mut self.editor {
            ed.on_exit(gl);
        }
    }
}
